#!/usr/bin/env python3
"""Convert the generated VLESS share-link list into a Mihomo/Clash Verge profile.

Input:  public/sub.txt (generated by vpngate.py)
Output: public/clash.yaml (JSON syntax, valid YAML 1.2)
"""

import json
import os
from urllib.parse import parse_qs, unquote, urlparse

PUBLIC_DIR = os.environ.get("PUBLIC_DIR", "public")
SOURCE = os.path.join(PUBLIC_DIR, "sub.txt")
# Use the Relay Worker hostname as the Clash server address.
# Override with EDT_DOMAIN (GitHub variable) when you bind a custom domain.
EDGE_SERVER = os.environ.get("EDT_DOMAIN", "cmos969-app-01.cmosliu969.workers.dev")
DEST = os.path.join(PUBLIC_DIR, "clash.yaml")


def convert_link(line):
    uri = urlparse(line.strip())
    if uri.scheme.lower() != "vless" or not uri.hostname:
        return None

    query = parse_qs(uri.query, keep_blank_values=True)

    def first(key, default=""):
        values = query.get(key)
        return values[0] if values else default

    if first("type") != "ws" or first("security") != "tls":
        raise ValueError(f"Unsupported VLESS transport/security in link: {line[:100]}")

    name = unquote(uri.fragment) or f"VLESS-{uri.hostname}"
    path = first("path")
    ws_host = first("host", uri.hostname)
    servername = first("sni", uri.hostname)

    proxy = {
        "name": name,
        "type": "vless",
        "server": EDGE_SERVER,
        "port": uri.port or 443,
        "uuid": uri.username,
        "tls": True,
        "servername": servername,
        "client-fingerprint": first("fp", "chrome"),
        "network": "ws",
        "ws-opts": {
            "path": path,
            "headers": {"Host": ws_host},
        },
    }
    return proxy


def main():
    with open(SOURCE, "r", encoding="utf-8") as f:
        links = [line.strip() for line in f if line.strip().lower().startswith("vless://")]

    proxies = []
    used_names = set()
    for line in links:
        proxy = convert_link(line)
        if proxy is None:
            continue
        original = proxy["name"]
        name = original
        suffix = 2
        while name in used_names:
            name = f"{original}-{suffix}"
            suffix += 1
        proxy["name"] = name
        used_names.add(name)
        proxies.append(proxy)

    if not proxies:
        raise SystemExit(f"No VLESS links found in {SOURCE}; refusing to publish an empty profile")

    names = [proxy["name"] for proxy in proxies]
    profile = {
        "mixed-port": 7890,
        "allow-lan": False,
        "mode": "rule",
        "log-level": "warning",
        # Resolve proxy-server hostnames over HTTPS; plain DNS on the current
        # network is returning incorrect addresses for workers.dev.
        "dns": {
            "enable": True,
            "ipv6": False,
            "enhanced-mode": "fake-ip",
            "nameserver": [
                "https://1.1.1.1/dns-query",
                "https://1.0.0.1/dns-query",
            ],
            "proxy-server-nameserver": [
                "https://1.1.1.1/dns-query",
                "https://1.0.0.1/dns-query",
            ],
        },
        "proxies": proxies,
        "proxy-groups": [
            {
                "name": "AUTO",
                "type": "url-test",
                "proxies": names,
                "url": "https://www.gstatic.com/generate_204",
                "interval": 300,
                "tolerance": 100,
            },
            {
                "name": "PROXY",
                "type": "select",
                "proxies": ["AUTO", "DIRECT", *names],
            },
        ],
        "rules": ["MATCH,PROXY"],
    }

    os.makedirs(PUBLIC_DIR, exist_ok=True)
    with open(DEST, "w", encoding="utf-8") as f:
        # JSON is a YAML 1.2 subset and avoids an extra YAML dependency.
        json.dump(profile, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Generated {DEST} with {len(proxies)} VLESS nodes")


if __name__ == "__main__":
    main()
